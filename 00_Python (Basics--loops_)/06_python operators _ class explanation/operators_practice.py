print("After += 5:", x)

print("a > b:", a > b)
print("a == b:", a == b)
print("a != b:", a != b)

print("Logical AND:", a > 10 and b < 10)
print("Logical OR:", a < 10 or b < 10)
print("Logical NOT:", not(a > b))

print("Unary plus:", +a)
